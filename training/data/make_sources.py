#!/usr/bin/env python3
"""Generate SOURCES.md from levels.json + build_report.json (both written by fetch_levels.py)."""
from __future__ import annotations

import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fetch_levels  # noqa: E402  (cached CDX parse: instant once fetch_levels.py has run)

ID_URL = "https://raw.githubusercontent.com/id-Software/DOOM/master/linuxdoom-1.10/d_englsh.h"

rows = json.load(open(os.path.join(HERE, "levels.json"), encoding="utf-8"))
rep = json.load(open(os.path.join(HERE, "build_report.json"), encoding="utf-8"))
wads = rep["wads"]
first_url: dict[str, str] = {}
for r in rows:
    first_url.setdefault(r["wad"], r["source_url"])

def null_reason(name: str) -> str:
    if fetch_levels.is_placeholder(name):
        return "placeholder / bare slot"
    if fetch_levels.FILENAME.search(name):
        return "contains a file name"
    t = name.replace("\u2019", "'").replace("\u2018", "'")
    if not t.isascii():
        return "non-ASCII character"
    if any(c.isdigit() for c in t):
        return "contains a digit"
    u = t.upper().replace("-", " ").replace("/", " ").replace(".", "")
    if any(c not in fetch_levels.ALLOWED for c in u):
        return "other symbol (, ? : & ( ) \" _ ...)"
    if not any(c.isalpha() for c in u):
        return "no letter"
    return f"longer than {fetch_levels.MAX_CLEAN} characters"


null_reasons = collections.Counter(null_reason(r["name"]) for r in rows if not r["clean"])
tier_order = ["official", "curated", "cacoward", "megawad", "small"]


def how(w: str, d: dict) -> str:
    if d.get("source") == "id d_englsh.h":
        return "C string literals `HUSTR_*`/`PHUSTR_*`/`THUSTR_*` parsed with a regex"
    if d.get("page_url") and d["page_levels"]:
        extra = []
        if d["page_only"]:
            extra.append(f"+{d['page_only']} only on page")
        if d["cdx_not_on_page"]:
            extra.append(f"{d['cdx_not_on_page']} CDX-only (cited via level article)")
        return (f"WAD article link titles ({d['page_levels']}) + Wayback CDX level-article titles ({d['cdx_level_articles']})"
                + (" [" + "; ".join(extra) + "]" if extra else ""))
    return f"Wayback CDX level-article titles ({d['cdx_level_articles']}); WAD article not fetchable"


def src(w: str, d: dict) -> str:
    if d.get("source") == "id d_englsh.h":
        return ID_URL
    if d.get("page_url") and d["page_levels"]:
        return d["page_url"]
    return first_url.get(w, "") + " (first of several level articles)" if first_url.get(w) else ""


def row(w: str) -> str:
    d = wads[w]
    return (f"| {w} | {d['tier']} | {src(w, d)} | {d['kept_clean']} | {d['raw_entries']} | {how(w, d)} |")


def table(ws: list[str]) -> str:
    out = ["| WAD | tier | source URL | clean names kept | entries before dedupe | extraction |", "|---|---|---|---:|---:|---|"]
    out += [row(w) for w in ws]
    return "\n".join(out)


by_tier: dict[str, list[str]] = collections.defaultdict(list)
for w, d in wads.items():
    by_tier[d["tier"]].append(w)
order_idx = {}
for i, r in enumerate(rows):
    order_idx.setdefault(r["wad"], i)
for t in by_tier:
    by_tier[t].sort(key=lambda w: order_idx.get(w, 10**9))

nclean = sum(1 for r in rows if r["clean"])
_arts = fetch_levels.cdx_level_articles()
n_cdx_articles, n_cdx_wads = len(_arts), len({v[3] for v in _arts.values()})
n_pages_ok = sum(1 for d in wads.values() if d.get("page_url") and d["page_levels"])
n_pages_failed = len(rep["page_fetch_failed"])
n_pages_both = sum(1 for d in wads.values() if d.get("page_url") and d["page_only"] == 0 and d["cdx_not_on_page"] == 0)
n_page_only = sum(d["page_only"] for d in wads.values() if d.get("page_url"))
n_cdx_not_page = sum(d["cdx_not_on_page"] for d in wads.values() if d.get("page_url"))
tier_summary = ["| tier | WADs | clean names kept | entries with clean=null |", "|---|---:|---:|---:|"]
for t in tier_order:
    ws = by_tier.get(t, [])
    tier_summary.append(f"| {t} | {len(ws)} | {sum(wads[w]['kept_clean'] for w in ws)} | {sum(wads[w]['null_clean'] for w in ws)} |")

doc = f"""# Sources for `levels.json`

Generated by `make_sources.py` from `levels.json` + `build_report.json`, which `fetch_levels.py` writes.
{nclean} unique non-null `clean` names, {len(rows)} entries, {len(wads)} WADs. Nothing is invented or completed:
a name is emitted only if it occurs verbatim in the cited page (title of a level article / link on the
WAD's article / C string literal in id's source).

## How the names were obtained

* **id Software source** (Doom E1-E4, Doom II, The Plutonia Experiment, TNT: Evilution = Final Doom):
  `{ID_URL}` fetched and parsed
  (`HUSTR_E*M*`, `HUSTR_1..32`, `PHUSTR_1..32`, `THUSTR_1..32`). Spelling and case are the source's (Doom II onward are lower case).
* **DoomWiki** (`https://doomwiki.org`) for everything else: Doom 64, SIGIL, SIGIL II, No Rest for the Living, Legacy of Rust,
  Master Levels and every community WAD. doomwiki.org returns a Cloudflare `403` to non-browser clients (`https://www.doomworld.com/idgames/` too), so pages were read from the **Internet Archive's copies**; `source_url` is the exact
  `https://web.archive.org/web/<timestamp>/https://doomwiki.org/wiki/<Title>` snapshot that was opened. (`/web/<ts>id_/` redirects to
  the capture nearest to `<ts>`, which can be a recorded 403 page, so several timestamps are tried and the result must look like a
  rendered article.)
  Two kinds of evidence:
  1. **WAD article link list**: every link on the WAD's article whose title has the shape `MAP07: Dead Simple (Doom II)` /
     `E2M3: Refinery (Doom)` and whose `(...)` suffix is that WAD's own article title. Cited with the WAD-article snapshot.
     The crawl covers only the official and curated tiers. Wayback answered in 5-60 s with frequent time-outs, so a full crawl of ~950 WADs was
     impractical. In this build {n_pages_ok} WAD articles supplied level links and {n_pages_failed} fetches failed
     (listed under *Skipped*). On the fetched pages, {n_page_only} link-title levels were not in the CDX index (added) and
     {n_cdx_not_page} CDX levels were not linked from the page (kept, cited via their level article).
  2. **Level articles**: the Wayback CDX index of all archived `doomwiki.org/wiki/MAP*` and `E?M*` article URLs with
     status 200 ({n_cdx_articles:,} level articles in {n_cdx_wads} WADs after dropping query/diff URLs; {n_cdx_wads - len(rep['excluded'])} WADs after excluding Heretic/Hexen/Strife titles). The article title is
     `<slot>: <Level name> (<WAD article title>)`. Levels not linked from the WAD article (or whose WAD article could not be
     fetched) are cited with the snapshot of the level's own article.
* Verification: `verify_levels.py sample` re-opens the cited URL (live, no cache) and looks for the exact
  `<slot>: <name> (<wad>)` title (DoomWiki) or the C string literal (id source).
* The WAD's own MAPINFO/DEHACKED lumps were **not** used: they need whole WAD downloads of 5–100 MB each, and the DoomWiki
  titles already carry the same names.

## Cleaning (`clean`)

Upper-case; `'` and `!` kept; typographic apostrophes (U+2018/U+2019) become `'`; `.` dropped; `-` and `/` become a space;
spaces collapsed and stripped. `clean = null` when the name contains a digit or any other character outside A-Z space `'` `!`
(`,` `?` `:` `&` `(` `)` `"` ... or non-ASCII letters such as `é`), contains a file name (`.wad`, `.deh`, ...), has no letter,
is longer than 23 characters, or is a placeholder (`Untitled`, `Unnamed`, `N/A`, `TBD`, `None`, `Unknown`, bare `MAP07`/`Level 3`).
Dedupe by `clean` keeps the first entry in this order: official (id source first, then Doom 64, SIGIL, SIGIL II, NRftL, Legacy of
Rust, Master Levels) > curated (a hand-picked list of well-known WADs, `CURATED` in `fetch_levels.py`) > cacoward (WADs linked from DoomWiki `Cacowards_2004`..`Cacowards_2025`)
> megawad (>= 9 level articles) > small (other WADs); inside a tier by WAD title then slot. Entries with `clean = null` are kept
(de-duplicated by name+wad+slot) so that the raw name list stays available.
`tier` is an extra field so a consumer can filter to the best-known WADs.

## Tier summary

{chr(10).join(tier_summary)}

## Why `clean` is null ({sum(null_reasons.values())} entries)

{chr(10).join(f"* {k}: {v}" for k, v in null_reasons.most_common())}

## Official games

{table(by_tier.get('official', []))}

## Curated WADs

{table(by_tier.get("curated", []))}

## Cacoward-linked WADs

{table(by_tier.get("cacoward", []))}

## Megawads / episodes (>= 9 level articles, not above)

{table(by_tier.get("megawad", []))}

## Small WADs (< 9 level articles)

{table(by_tier.get("small", []))}

## Skipped

* WAD-article fetch failures in the official/curated crawl (their names are still in `levels.json`, cited via level articles
  instead of the WAD article): {", ".join(rep["page_fetch_failed"]) or "none"}.
* Excluded as other franchises (Heretic / Hexen / Strife titles; level articles dropped): {json.dumps(rep["excluded"], ensure_ascii=False)}.
* Not collected: official Doom 3 / DOOM (2016) / DOOM Eternal / Doom: The Dark Ages levels (outside the scope of this corpus);
  names inside WAD lumps (MAPINFO/UMAPINFO/DEHACKED/ZMAPINFO) from the idgames archive (needs whole-WAD downloads; `https://www.doomworld.com/idgames/`
  returned HTTP 403 from this host); WADs without DoomWiki level articles in the Wayback index
  (not countable from here); level articles that no Wayback capture with status 200 exists for.
* "Final Doom" has no separate entry: its two WADs are `TNT: Evilution` and `The Plutonia Experiment` (id source, tier official).
"""
open(os.path.join(HERE, "SOURCES.md"), "w", encoding="utf-8").write(doc)
print("wrote SOURCES.md", len(doc))
